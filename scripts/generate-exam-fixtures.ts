async function pdf(name: string, body: string, rtl = true) {
  await page.setContent(
    `<html lang="fa" dir="${rtl ? "rtl" : "ltr"}"><meta charset="utf-8"><style>body{font-family:Arial,sans-serif;font-size:24px;line-height:1.8;padding:25px}p{margin:8px}table{border-collapse:collapse;width:90%}td,th{border:1px solid;padding:8px}</style>${body}</html>`,
  );
  await page.pdf({
    path: `${root}/${name}.pdf`,
    format: "A4",
    printBackground: true,
  });
}
async function scan(name: string, source: string) {
  const path = `/tmp/hodhod-fixture-${name}`;
  execFileSync("pdftoppm", [
    "-scale-to",
    "1600",
    "-f",
    "1",
    "-l",
    "1",
    "-png",
    "-singlefile",
    `${root}/${source}.pdf`,
    path,
  ]);
  const jpeg = await sharp(path + ".png")
    .jpeg({ quality: 95 })
    .toBuffer();
  const meta = await sharp(jpeg).metadata();
  const content = "q 595 0 0 842 0 0 cm /Im0 Do Q";
  const objs = [
    Buffer.from("<< /Type /Catalog /Pages 2 0 R >>"),
    Buffer.from("<< /Type /Pages /Kids [3 0 R] /Count 1 >>"),
    Buffer.from(
      "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /XObject << /Im0 4 0 R >> >> /Contents 5 0 R >>",
    ),
    Buffer.concat([
      Buffer.from(
        `<< /Type /XObject /Subtype /Image /Width ${meta.width} /Height ${meta.height} /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length ${jpeg.length} >>\nstream\n`,
      ),
      jpeg,
      Buffer.from("\nendstream"),
    ]),
    Buffer.from(
      `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
    ),
  ];
  let buf = Buffer.from("%PDF-1.4\n");
  const offsets = [0];
  for (const [i, obj] of objs.entries()) {
    offsets.push(buf.length);
    buf = Buffer.concat([
      buf,
      Buffer.from(`${i + 1} 0 obj\n`),
      obj,
      Buffer.from("\nendobj\n"),
    ]);
  }
  const xref = buf.length;
  buf = Buffer.concat([
    buf,
    Buffer.from(
      "xref\n0 6\n0000000000 65535 f \n" +
        offsets
          .slice(1)
          .map((n) => String(n).padStart(10, "0") + " 00000 n \n")
          .join("") +
        `trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`,
    ),
  ]);
  await writeFile(`${root}/${name}.pdf`, buf);
  return path + ".png";
}
